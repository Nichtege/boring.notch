            } header: {
                Text("System features")
            }

            Section {
                Defaults.Toggle(key: .showNotificationsInNotch) {
                    Text("Show notifications in the notch")
                }
                HStack {
                    Text("Accessibility access")
                    Spacer()
                    (accessibilityAuthorized ? Text("Allowed") : Text("Missing"))
                        .foregroundStyle(.secondary)
                }
